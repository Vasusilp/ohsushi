create table sessions (
  id bigint generated by default as identity primary key,
  table_number int not null,
  adult_count int not null default 0,
  child_count int not null default 0,
  status text not null default 'open',
  created_at timestamptz not null default now()
);
create table menu_categories (
  id bigint generated by default as identity primary key,
  name text not null,
  sort_order int not null default 0
);
create table menu_items (
  id bigint generated by default as identity primary key,
  category_id bigint references menu_categories(id),
  name text not null
);
create table orders (
  id bigint generated by default as identity primary key,
  session_id bigint references sessions(id),
  table_number int not null,
  items jsonb not null,
  status text not null default 'received',
  created_at timestamptz not null default now()
);
alter table sessions enable row level security;
alter table menu_categories enable row level security;
alter table menu_items enable row level security;
alter table orders enable row level security;
create policy "allow all - sessions" on sessions for all using (true) with check (true);
create policy "allow all - menu_categories" on menu_categories for all using (true) with check (true);
create policy "allow all - menu_items" on menu_items for all using (true) with check (true);
create policy "allow all - orders" on orders for all using (true) with check (true);

